// PreToolUse hook: stop Claude from hand-editing files that a build step
// regenerates. Exit code 2 blocks the edit and shows the message to Claude,
// so it edits the real source instead.
//
// Shared verbatim between cleaningkit and analysiskit; rules for a file that
// does not exist in a repo simply never match.

const fs = require("fs");
const path = require("path");

let raw = "";
process.stdin.on("data", (chunk) => (raw += chunk));
process.stdin.on("end", () => {
  let input;
  try {
    input = JSON.parse(raw);
  } catch {
    process.exit(0); // never block on a malformed payload
  }

  const file = input?.tool_input?.file_path || input?.tool_input?.notebook_path;
  if (!file) process.exit(0);

  const root = process.env.CLAUDE_PROJECT_DIR || input.cwd || process.cwd();
  let rel = path.relative(root, path.resolve(root, file)).split(path.sep).join("/");
  if (rel.startsWith("..")) process.exit(0); // outside the project

  // Claude worktrees live inside the repo; judge the path inside the worktree.
  rel = rel.replace(/^\.claude\/worktrees\/[^/]+\//, "");
  const worktreeRoot = path.resolve(root, file).slice(0, -rel.length);

  const rules = [
    {
      test: /^man\/.*\.Rd$/i,
      why: "man/*.Rd is generated by roxygen2. Edit the #' comments in R/ and run devtools::document().",
    },
    {
      test: /^NAMESPACE$/,
      why: "NAMESPACE is generated by roxygen2. Use @export / @importFrom tags in R/ and run devtools::document().",
    },
    {
      test: /^docs\//i,
      why: "docs/ is the pkgdown site, built by pkgdown::build_site() (and by CI). Edit R/, vignettes/, README or _pkgdown.yml instead.",
    },
    {
      test: /^README\.md$/i,
      when: () => fs.existsSync(path.join(worktreeRoot, "README.Rmd")),
      why: "README.md is knitted from README.Rmd. Edit README.Rmd and run devtools::build_readme().",
    },
    {
      test: /^inst\/extdata\/.*\.bin$/i,
      why: "The .bin VBA project is built in Excel from inst/vba/*.bas / *.cls by dev/build_vba_bin.R. Edit the sources and ask the user to rebuild.",
    },
  ];

  const hit = rules.find((r) => r.test.test(rel) && (!r.when || r.when()));
  if (hit) {
    process.stderr.write(`Blocked edit to ${rel}: ${hit.why}\n`);
    process.exit(2);
  }
  process.exit(0);
});
